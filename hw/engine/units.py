import sys

# the ML branch's generator, parser and reference, vendored unmodified under hw/isaforge
sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
from isaforge.features import parse_formula  # noqa: E402
from isaforge.rtl import BOUNDARIES, evaluate_formula, generate_rtl  # noqa: E402

# PROVISIONAL: up to 3 fused units on custom-0 (0x0b), funct7=2, funct3 = slot number
MAX_UNITS = 3
FUNCT7 = 2
MULS = {"mul", "mulh", "mulhu", "mulhsu"}
SEED = 20261020
RANDOM_PAIRS = 1000
TIMED = 64
MASK = (1 << 32) - 1


def ops(node):
    yield node.value
    for child in node.children:
        yield from ops(child)


def reference(node, in0, in1):
    # a second evaluator written apart from the ML branch's, so a shared parsing bug can't hide
    if not node.children:
        if node.value == "in0":
            return in0
        if node.value == "in1":
            return in1
        return node.value & MASK
    v = [reference(c, in0, in1) for c in node.children]
    s = [x - (1 << 32) if x >> 31 else x for x in v]
    op = node.value
    table = {
        "lui": lambda: v[0], "add": lambda: v[0] + v[1], "addi": lambda: v[0] + v[1],
        "sub": lambda: v[0] - v[1], "and": lambda: v[0] & v[1], "andi": lambda: v[0] & v[1],
        "or": lambda: v[0] | v[1], "ori": lambda: v[0] | v[1], "xor": lambda: v[0] ^ v[1],
        "xori": lambda: v[0] ^ v[1], "sll": lambda: v[0] << (v[1] & 31), "slli": lambda: v[0] << (v[1] & 31),
        "srl": lambda: v[0] >> (v[1] & 31), "srli": lambda: v[0] >> (v[1] & 31),
        "sra": lambda: s[0] >> (v[1] & 31), "srai": lambda: s[0] >> (v[1] & 31),
        "slt": lambda: int(s[0] < s[1]), "slti": lambda: int(s[0] < s[1]),
        "sltu": lambda: int(v[0] < v[1]), "sltiu": lambda: int(v[0] < v[1]),
        "mul": lambda: v[0] * v[1], "mulh": lambda: (s[0] * s[1]) >> 32,
        "mulhsu": lambda: (s[0] * v[1]) >> 32, "mulhu": lambda: (v[0] * v[1]) >> 32,
    }
    return table[op]() & MASK


def candidateSize(formula):
    # the finder's size (distinct instructions), looked up in its output for any program
    for path in sorted(glob.glob("generated/candidates/*.json")):
        for c in json.load(open(path)):
            if c["formula"] == formula:
                return c["size"]
    raise SystemExit(f"{formula} is in no generated/candidates/*.json, so its size is unknown")


def plan(entries, allowMul):
    # validates the request and gives each formula a slot; list order is the rewrite priority
    if not 1 <= len(entries) <= MAX_UNITS:
        raise SystemExit(f"{len(entries)} formulas; one core takes 1 to {MAX_UNITS}")
    slots, flagged = [], []
    for i, entry in enumerate(entries):
        tree = parse_formula(entry["formula"])
        canonical = tree.canonical()
        if any(s["formula"] == canonical for s in slots):
            raise SystemExit(f"{canonical} is listed twice")
        hasMul = bool(MULS & set(ops(tree)))
        if hasMul:
            flagged.append(canonical)
        inputs = sorted({o for o in ops(tree) if o in ("in0", "in1")})
        slots.append({"slot": i, "funct7": FUNCT7, "funct3": i, "formula": canonical,
                      "module": f"cx_s{i}", "size": entry.get("size") or candidateSize(canonical),
                      "inputs": inputs, "has_mul": hasMul, "source": entry.get("benchmark")})
    if flagged and not allowMul:
        raise SystemExit("MUL FLAGGED (a combinational multiplier is expensive on iCE40; "
                         "rerun with ALLOW_MUL=1 to build anyway): " + ", ".join(flagged))
    key = json.dumps([s["formula"] for s in slots])
    return {"id": hashlib.sha256(key.encode()).hexdigest()[:12], "provisional": True, "slots": slots,
            "priority": [s["formula"] for s in slots]}


def decoder(manifest):
    # the PCPI unit: one decode per slot, one shared result register, acknowledged the cycle after
    # the first valid edge like the dry run's pcpi_fused.v; other encodings are left to trap
    slots = manifest["slots"]
    lines = ["// Generated by hw/engine/units.py (PROVISIONAL engine build " + manifest["id"] + ").",
             "// custom-0, funct7=2, funct3=slot: rd = cx_s<slot>(rs1, rs2)"]
    lines += [f"//   slot {s['slot']}: {s['formula']}" for s in slots]
    lines += ["module pcpi_engine (", "    input clk, resetn, valid,", "    input [31:0] insn, rs1, rs2,",
              "    output wr, wait_req, ready,", "    output [31:0] rd", ");"]
    for s in slots:
        match = (FUNCT7 << 25) | (s["funct3"] << 12) | 0x0B
        lines.append(f"    wire [31:0] v{s['slot']};")
        lines.append(f"    {s['module']} u{s['slot']}(.in0(rs1), .in1(rs2), .result(v{s['slot']}));")
        lines.append(f"    wire hit{s['slot']} = valid && (insn & 32'hfe00707f) == 32'h{match:08x};")
    hits = " || ".join(f"hit{s['slot']}" for s in slots)
    # one slot needs no select; with more, each result is gated by its own decode
    value = "v0" if len(slots) == 1 else " | ".join(f"({{32{{hit{s['slot']}}}}} & v{s['slot']})" for s in slots)
    lines += [f"    wire recognized = {hits};", f"    wire [31:0] value = {value};",
              "    reg active;", "    reg [31:0] result;", "    always @(posedge clk) begin",
              "        if (!resetn || !valid) begin", "            active <= 0;", "            result <= 0;",
              "        end else if (recognized && !active) begin", "            result <= value;",
              "            active <= 1;", "        end", "    end",
              "    assign ready = recognized && active;", "    assign wr = ready;",
              "    assign wait_req = recognized && !ready;", "    assign rd = result;", "endmodule", ""]
    return "\n".join(lines)


# --- microtests: bare programs for the unmodified harness, like the dry run's

TAIL = """
pass:
    li      a0, 1
    j       finish
fail:
    slli    a0, s3, 1
    ori     a0, a0, 1
finish:
    la      t0, tohost
    sw      a0, 0(t0)
hang:
    j       hang

    .section .tohost, "aw", @progbits
    .align  6
    .globl  tohost
tohost:   .dword 0
    .align  6
    .globl  fromhost
fromhost: .dword 0
    .section .bss
    .align  2
    .globl  instret_start, instret_stop
instret_start: .word 0
instret_stop:  .word 0
"""
HEAD = """    .section .text.start, "ax", @progbits
    .globl _start
_start:
    la      sp, __stack_top
    li      s3, 0
"""
WINDOW = ("    csrr    t5, instret\n    la      t6, instret_{0}\n    sw      t5, 0(t6)\n")


def insn(funct3, rd, rs1, rs2, funct7=FUNCT7, opcode=0x0B):
    return f".insn r {opcode:#x}, {funct3}, {funct7}, {rd}, {rs1}, {rs2}"


def vectors(slot):
    # boundary pairs, byte-edge pairs and seeded random pairs, checked by both references
    tree = parse_formula(slot["formula"])
    edges = (0x00, 0x7F, 0x80, 0xFF, 0x100, 0xFFFFFF00, 0xFFFFFFFF, 0xA5A5A5A5, 0x5A5A5A5A)
    pairs = list(itertools.product(BOUNDARIES, repeat=2)) + list(itertools.product(edges, repeat=2))
    rng = random.Random(SEED + slot["slot"])
    pairs += [(rng.getrandbits(32), rng.getrandbits(32)) for _ in range(RANDOM_PAIRS)]
    out = []
    for a, b in pairs:
        want = evaluate_formula(tree, a, b)
        if want != reference(tree, a, b):
            raise SystemExit(f"the two references disagree on {slot['formula']} for {a:#x}, {b:#x}")
        out.append((a, b, want))
    return out


def checkProgram(slots):
    # every vector through every slot, then rd/rs aliasing cases; a failure exits with its check number
    body, data, checks = HEAD, "", 0
    for s in slots:
        table = vectors(s)
        body += f"""    la      s0, vectors{s['slot']}
    li      s1, {checks + len(table)}
check{s['slot']}:
    lw      t0, 0(s0)
    lw      t1, 4(s0)
    lw      t2, 8(s0)
    addi    s3, s3, 1
    {insn(s['funct3'], 't3', 't0', 't1')}
    bne     t3, t2, fail
    addi    s0, s0, 12
    bne     s3, s1, check{s['slot']}
"""
        checks += len(table)
        data += f"vectors{s['slot']}:\n" + "".join(f"    .word {a:#010x}, {b:#010x}, {w:#010x}\n" for a, b, w in table)
        tree = parse_formula(s["formula"])
        a, b = 0x12345678, 0x80000F0F
        for rd, rs1, rs2, x, y in (("t0", "t0", "t1", a, b), ("t1", "t0", "t1", a, b),
                                   ("t3", "t0", "t0", a, a), ("zero", "t0", "t1", a, b)):
            want = 0 if rd == "zero" else reference(tree, x, y)
            body += f"""    addi    s3, s3, 1
    li      t0, {a:#x}
    li      t1, {b:#x}
    li      t3, 0x55555555
    {insn(s['funct3'], rd, rs1, rs2)}
    li      t2, {want:#x}
    bne     {rd}, t2, fail
"""
            if rd == "zero":
                body += "    li      t2, 0x55555555\n    bne     t3, t2, fail\n"
            checks += 1
    body += "    j       pass\n" + TAIL + "\n    .section .rodata\n    .align 2\n" + data
    return body, checks


def timingProgram(line, repeat):
    # one harness window around `repeat` copies, so two lengths give cycles per instruction
    body = HEAD + "    li      t0, 0x12345678\n    li      t1, 0x9abcdef0\n" + WINDOW.format("start")
    body += f"    {line}\n" * repeat
    return body + WINDOW.format("stop") + "    j       pass\n" + TAIL


def trapProgram(line):
    return HEAD + f"    li      t0, 1\n    li      t1, 2\n    {line}\n    j       pass\n" + TAIL


def microtests(manifest):
    # name -> (assembly, what the run must do, which core)
    slots = manifest["slots"]
    text, checks = checkProgram(slots)
    out = {"micro-check": (text, "pass", "engine")}
    for s in slots:
        for n in (1, 2):
            out[f"micro-s{s['slot']}-{n}x"] = (timingProgram(insn(s["funct3"], "t3", "t0", "t1"), n * TIMED),
                                               "pass", "engine")
        out[f"trap-stock-s{s['slot']}"] = (trapProgram(insn(s["funct3"], "t3", "t0", "t1")), "trap", "stock")
    for n in (1, 2):
        out[f"micro-xor-{n}x"] = (timingProgram("xor     t3, t0, t1", n * TIMED), "pass", "engine")
    used = {s["funct3"] for s in slots}
    for f3 in range(8):
        if f3 not in used:
            out[f"trap-f3-{f3}"] = (trapProgram(insn(f3, "t3", "t0", "t1")), "trap", "engine")
    out["trap-f7-1"] = (trapProgram(insn(0, "t3", "t0", "t1", funct7=1)), "trap", "engine")
    out["trap-f7-3"] = (trapProgram(insn(0, "t3", "t0", "t1", funct7=3)), "trap", "engine")
    out["trap-custom1"] = (trapProgram(insn(0, "t3", "t0", "t1", opcode=0x2B)), "trap", "engine")
    return out, checks


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--candidates", required=True)
    parser.add_argument("--root", default="generated/hw/engine")
    parser.add_argument("--allow-mul", action="store_true")
    parser.add_argument("--id-only", action="store_true")
    args = parser.parse_args()

    entries = json.load(open(args.candidates))
    manifest = plan(entries, args.allow_mul)
    if args.id_only:
        print(manifest["id"])
        return
    build = os.path.join(args.root, manifest["id"])
    for sub in ("rtl", "micro"):
        os.makedirs(os.path.join(build, sub), exist_ok=True)

    files = ["hw/rtl/picorv32.v", "hw/rtl/core_top.v", f"{build}/rtl/pcpi_engine.v"]
    for s in manifest["slots"]:
        path = f"{build}/rtl/{s['module']}.v"
        with open(path, "w") as f:
            f.write(f"// Generated by hw/engine/units.py with hw/isaforge/rtl.py\n// formula: {s['formula']}\n")
            f.write(generate_rtl(s["formula"], s["module"]))
        files.append(path)
    with open(f"{build}/rtl/pcpi_engine.v", "w") as f:
        f.write(decoder(manifest))
    with open(f"{build}/rtl/files.txt", "w") as f:
        f.write(" ".join(files) + "\n")
    # the baseline's synthesis with FUSED=2, which selects pcpi_engine in core_top
    with open(f"{build}/engine.ys", "w") as f:
        f.write(f"read_verilog {' '.join(files)}\nchparam -set FUSED 2 core_top\nsynth_ice40 -top core_top\n"
                f"check -assert\nwrite_json {build}/synth/core_top.json\ntee -o {build}/synth/stat.txt stat\n")

    tests, checks = microtests(manifest)
    manifest["microtests"] = {name: {"expect": expect, "core": core} for name, (_, expect, core) in tests.items()}
    manifest["micro_checks"] = checks
    for name, (text, _, _) in tests.items():
        with open(f"{build}/micro/{name}.S", "w") as f:
            f.write(text)
    with open(f"{build}/manifest.json", "w") as f:
        json.dump(manifest, f, indent=1)
    print(build)


if __name__ == "__main__":
    main()
