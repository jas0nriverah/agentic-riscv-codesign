import argparse
import os
import sys

# the ML branch's generator, vendored unmodified under hw/isaforge
sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
from isaforge.rtl import generate_rtl  # noqa: E402


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--formula", required=True)
    parser.add_argument("--module", required=True)
    parser.add_argument("--out", required=True)
    args = parser.parse_args()

    # the header says where the file came from so nobody edits it by hand
    header = (f"// Generated by hw/dryrun/gen_rtl.py with hw/isaforge/rtl.py (ML branch, unmodified).\n"
              f"// Do not edit: rerun `make hw-dryrun-rtl`.\n"
              f"// formula: {args.formula}\n")
    with open(args.out, "w") as out:
        out.write(header + generate_rtl(args.formula, args.module))


if __name__ == "__main__":
    main()
